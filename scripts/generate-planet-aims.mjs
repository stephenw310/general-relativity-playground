import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createRequire } from "node:module";
import ts from "typescript";

const directory = mkdtempSync(join(tmpdir(), "planet-aims-"));
try {
  for (const name of ["descent-physics", "descent-planet-trace"]) {
    writeFileSync(
      join(directory, `${name}.js`),
      ts.transpileModule(
        readFileSync(
          new URL(`../src/utils/${name}.ts`, import.meta.url),
          "utf8",
        ),
        {
          compilerOptions: {
            module: ts.ModuleKind.CommonJS,
            target: ts.ScriptTarget.ES2020,
          },
        },
      ).outputText,
    );
  }
  const require = createRequire(import.meta.url);
  const { tracePlanetView } = require(
    join(directory, "descent-planet-trace.js"),
  );
  const { START_RADIUS, END_RADIUS } = require(
    join(directory, "descent-physics.js"),
  );
  const rows = [];
  for (let index = 0; index <= 512; index++) {
    const radius = START_RADIUS * (END_RADIUS / START_RADIUS) ** (index / 512);
    const { yaw, pitch } = tracePlanetView(radius);
    rows.push(`  [${Number(yaw.toFixed(9))}, ${Number(pitch.toFixed(9))}],`);
  }
  writeFileSync(
    new URL("../src/utils/descent-planet-aims.ts", import.meta.url),
    "// Generated by node scripts/generate-planet-aims.mjs.\n" +
      "// 513 samples uniformly spaced in log radius, from START_RADIUS to END_RADIUS.\n" +
      "// Regenerate when the planet direction, flight inclination, or ray solver changes.\n" +
      "export const PLANET_AIMS: readonly (readonly [number, number])[] = [\n" +
      rows.join("\n") +
      "\n];\n",
  );
  console.log("Generated 513 planet aim samples.");
} finally {
  rmSync(directory, { recursive: true, force: true });
}
